// Regenerate the typed API client from the FastAPI app's OpenAPI schema (no server needed):
//   npm run gen:api   ->  src/api/schema.d.ts
import { execFileSync } from "node:child_process"
import { existsSync, mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "../..")
const python = existsSync(path.join(repo, ".venv/bin/python")) ? path.join(repo, ".venv/bin/python") : "python3"

const json = execFileSync(python, ["-c", "import json; from server.app import create_app; print(json.dumps(create_app().openapi()))"],
  { cwd: repo, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 })
const ast = await openapiTS(JSON.parse(json))
const out = path.resolve(here, "../src/api/schema.d.ts")
mkdirSync(path.dirname(out), { recursive: true })
writeFileSync(out, "// Generated by `npm run gen:api` from the FastAPI OpenAPI schema. Do not edit.\n\n" + astToString(ast))
console.log(`wrote ${path.relative(process.cwd(), out)}`)
